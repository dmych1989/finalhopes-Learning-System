def aux_stars(year_gan_idx, year_zhi_idx, lunar_month, hour_zhi_idx,
              ming_zhi_idx, shen_zhi_idx, gender, ju_name, lunar_day):
    """计算辅星与杂曜落宫，返回 [(name, zhi_index_子0, kind), ...]。

    lunar_month: 农历月序（1-12，闰月取同序数）；hour_zhi_idx: 时辰地支序；
    ming_zhi_idx/shen_zhi_idx: 命宫/身宫地支序（子0）；ju_name: 五行局全名；
    lunar_day: 农历日序（1-30）；gender: '男'/'女'。
    """
    g, z, m, h = year_gan_idx, year_zhi_idx, lunar_month, hour_zhi_idx
    z0 = z                       # 年支子0序
    sh = SANHE[z0]
    luc = _LU[g]
    ma = _MA[sh]
    out = []
    # ---- 辅星（14，标准 iztro 集，已与 iztro 真值校准）----
    out.append(("左辅", (4 + m - 1) % 12, "minor"))
    out.append(("右弼", (11 - m) % 12, "minor"))
    out.append(("文昌", (10 - h) % 12, "minor"))
    out.append(("文曲", (h + 4) % 12, "minor"))
    out.append(("天魁", TIANKUI[g], "minor"))
    out.append(("天钺", TIANYUE[g], "minor"))
    out.append(("禄存", luc, "minor"))
    out.append(("天马", ma, "minor"))
    out.append(("擎羊", (luc + 1) % 12, "minor"))
    out.append(("陀罗", (luc - 1) % 12, "minor"))
    out.append(("火星", Z0((_HUO[sh] + h) % 12), "minor"))
    out.append(("铃星", Z0((_LING[sh] + h) % 12), "minor"))
    out.append(("地空", (11 - h) % 12, "minor"))
    out.append(("地劫", (h + 11) % 12, "minor"))
    # ---- 杂曜（标准 iztro 集 + 天纪专属）----
    # 红鸾 / 天喜（年支）
    hl = (3 - z0) % 12
    out.append(("红鸾", hl, "adjective"))
    out.append(("天喜", (hl + 6) % 12, "adjective"))
    # 华盖 / 咸池（年支三合）
    _hg = {1: (_H['戌'], _H['卯']), 0: (_H['辰'], _H['酉']),
           3: (_H['丑'], _H['午']), 2: (_H['未'], _H['子'])}[sh]
    out.append(("华盖", Z0(_hg[0]), "adjective"))
    out.append(("咸池", Z0(_hg[1]), "adjective"))
    # 孤辰 / 寡宿（按年支四季组，对齐 iztro getGuGuaIndex）
    out.append(("孤辰", _GUCHEN[z0], "adjective"))
    out.append(("寡宿", _GUASU[z0], "adjective"))
    # 天才（命宫起子顺至年支）/ 天寿（身宫起子顺至年支）
    out.append(("天才", (ming_zhi_idx + z0) % 12, "adjective"))
    out.append(("天寿", (shen_zhi_idx + z0) % 12, "adjective"))
    # 天刑（酉宫起正月顺至生月）
    out.append(("天刑", (8 + m) % 12, "adjective"))
    # 天姚 / 阴煞 / 天月 / 天巫（生月）
    out.append(("天姚", m % 12, "adjective"))
    out.append(("阴煞", Z0(_YINSHA[(m - 1) % 6]), "adjective"))
    out.append(("天月", Z0(_TIANYUE_M[(m - 1) % 12]), "adjective"))
    out.append(("天巫", Z0(_TIANWU[(m - 1) % 4]), "adjective"))
    # 月解（解神月，正二申…）
    out.append(("月解", Z0(_YUEJIE[(m - 1) // 2]), "adjective"))
    # 天厨 / 破碎 / 蜚廉 / 龙池 / 凤阁 / 天哭 / 天虚 / 天官 / 天福 / 天德 / 月德 / 天空 / 截路 / 空亡（年干支）
    out.append(("天厨", Z0(_TIANCHU[g]), "adjective"))
    out.append(("破碎", Z0([3, 11, 7][z0 % 3]), "adjective"))
    out.append(("蜚廉", Z0(_FEILIAN[z0]), "adjective"))
    out.append(("龙池", Z0((_H['辰'] + z0) % 12), "adjective"))
    out.append(("凤阁", Z0((_H['戌'] - z0) % 12), "adjective"))
    out.append(("天哭", Z0((_H['午'] - z0) % 12), "adjective"))
    out.append(("天虚", Z0((_H['午'] + z0) % 12), "adjective"))
    out.append(("天官", Z0(_TIANGUAN[g]), "adjective"))
    out.append(("天福", Z0(_TIANFU[g]), "adjective"))
    out.append(("天德", Z0((_H['酉'] + z0) % 12), "adjective"))
    out.append(("月德", Z0((_H['巳'] + z0) % 12), "adjective"))
    out.append(("天空", (z0 + 1) % 12, "adjective"))
    out.append(("截路", Z0(_JIELU[g % 5]), "adjective"))
    out.append(("空亡", Z0(_KONGWANG[g % 5]), "adjective"))
    # 旬空（天纪规则，与 APK 最终覆盖一致）/ 旬中
    xk = tianji_xunkong(GAN[g], ZHI[z])
    out.append(("旬空", xk["kong"], "adjective"))
    out.append(("旬中", xk["zhong"], "adjective"))
